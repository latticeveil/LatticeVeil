    private void EmboldenGlyphs()
    {
        var keys = new List<char>(_glyphs.Keys);
        foreach (var key in keys)
        {
            var rows = _glyphs[key];
            var expanded = new byte[_h];
            for (int row = 0; row < _h; row++)
            {
                var bits = rows[row] & 0b1_1111;
                var widened = bits | (bits >> 1);
                expanded[row] = (byte)(widened & 0b1_1111);
            }

            _glyphs[key] = expanded;
        }
    }
